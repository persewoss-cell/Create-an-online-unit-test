// 정답지를 보고 이 사이트 정답 규칙에 맞는 "번호<탭>정답" 표를 만들게 한다 → 정답 엑셀 양식에 그대로 붙여 넣기

import { answerHint } from './answerSheet.js';

/** 이 사이트가 알아듣는 정답 쓰는 법 (엑셀 양식의 "작성 방법" 시트와 같은 규칙) */
const RULES = [
  '객관식: 정답 번호 하나만. 4 또는 ④ (답이 여러 개면 2, 4)',
  '㉮㉯㉰ / ㉠㉡㉢ 기호로 고르는 문제: ㉮ (여러 개면 ㉮, ㉰)',
  '(1)(2)(3) 중 ○표 하는 문제: (3)',
  '○표 할 괄호(왼쪽/오른쪽 등)를 고르는 문제: 오른쪽 (또는 왼쪽, 가운데, 위, 아래)',
  'O/X 문제: O 또는 X',
  '선 잇기: (1)-① (2)-③ (3)-② 처럼 짝을 모두',
  '단답형: 답만 그대로. 단위가 있으면 단위까지 (예: 3 cm, 15 L)',
  '단답형에서 여러 답을 모두 정답으로 인정: / 로 구분 (예: 로제타 선생님 / 로제타)',
  '답 칸(□, ( ))이 여러 개이거나 모두 써야 정답인 답: 순서대로 쉼표 (예: 3, 6, 9 / 산소, 이산화 탄소)',
  '서술형: 모범 답안 한 문장 그대로. 반드시 들어가야 할 낱말이 정답지에 있으면 문장 뒤에 핵심어: 낱말1, 낱말2',
  '서술형인데 정답지에 "(예)", "예시 답안"처럼 여러 예가 있으면: (예) 답1 / 답2',
  '한 문항에 답 종류가 여러 부분(예: 객관식 + 단답)이면: 부분마다 ; 로 구분 (예: ③ ; 3 cm)',
  '그림을 그리는 문항: 그리기 (그림 + 괄호 답이 함께 있으면 그리기 + 3 cm)',
  '정답이 정해지지 않았거나(자유 답) 선생님이 직접 봐야 하는 문항: 검토',
];

/**
 * @param {object[]} questions 이 평가의 문항(인식 결과) — 문항마다 답 쓰는 법 안내를 붙인다
 * @param {string} title 평가 이름
 */
export function buildAnswerPrompt(questions, title = '') {
  const nos = questions.map((q) => Number(q.no)).filter(Boolean);
  const first = nos.length ? Math.min(...nos) : 1;
  const last = nos.length ? Math.max(...nos) : 1;
  const lines = [
    `너는 초등학교 단원평가 정답을 정리하는 도우미야. 함께 보내는 정답지(PDF·사진 또는 붙여 넣은 글)를 보고,${title ? ` "${title}"의` : ''} 정답을 아래 규칙대로 엑셀에 바로 붙여 넣을 수 있는 표로 만들어 줘.`,
    '',
    '[출력 형식 — 꼭 지켜 줘]',
    '- 코드 블록 하나 안에, 첫 줄은 번호<탭>정답, 그 아래로 한 줄에 한 문항씩 번호<탭>정답.',
    '- 번호와 정답 사이는 반드시 탭(Tab) 한 번. 번호는 숫자만(1, 2, 3 …).',
    `- 이 평가는 ${first}번부터 ${last}번까지 ${questions.length}문항이야. 빠진 번호 없이 모두 적어 줘.`,
    '- 해설, 풀이, 배점, 채점 기준, "정답:" 같은 머리말은 쓰지 마. 정답만.',
    '- 정답지에서 정답을 찾을 수 없거나 확실하지 않은 문항은 정답 칸에 검토 라고 적어 줘.',
    '- 표 밖에는 아무 설명도 쓰지 마.',
    '',
    '[정답 쓰는 규칙]',
    ...RULES.map((r) => `- ${r}`),
    '',
    '[문항별 안내 — 문제지를 보고 이 사이트가 미리 알아낸 답 형식]',
    ...questions.map((q) => `- ${q.no}번: ${answerHint(q)}`),
    '',
    '[출력 예시]',
    '```',
    '번호\t정답',
    '1\t③',
    '2\t3 cm',
    '3\t(1)-② (2)-① (3)-③',
    '```',
  ];
  return lines.join('\n');
}
