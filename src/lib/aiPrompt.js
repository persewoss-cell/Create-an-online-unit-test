// AI 채팅(ChatGPT·Gemini·Claude 등)에 붙여 넣을 명령어(프롬프트):
// 정답지를 보고 이 사이트 정답 규칙에 맞는 정답(+배점)을 문항 순서대로 한 줄씩 나열하게 한다
// → 정답 엑셀 양식의 B2 칸(첫 문항 정답 칸)에 그대로 붙여 넣기 (배점이 있으면 C 칸에 함께 들어감)

import { answerHint } from './answerSheet.js';

/** 이 사이트가 알아듣는 정답 쓰는 법 (엑셀 양식의 "작성 방법" 시트와 같은 규칙) */
const RULES = [
  '객관식: 정답 번호 하나만. 4 또는 ④ (답이 여러 개면 2, 4)',
  '㉮㉯㉰ / ㉠㉡㉢ 기호로 고르는 문제: ㉮ (여러 개면 ㉮, ㉰)',
  '(1)(2)(3) 중 ○표 하는 문제: (3)',
  '○표 할 괄호(왼쪽/오른쪽 등)를 고르는 문제: 오른쪽 (또는 왼쪽, 가운데, 위, 아래)',
  'O/X 문제: O 또는 X',
  '선 잇기: (1)-① (2)-③ (3)-② 처럼 짝을 모두',
  '단답형: 답만 그대로. 단위가 있으면 단위까지 (예: 3 cm, 15 L)',
  '단답형에서 여러 답을 모두 정답으로 인정: / 로 구분 (예: 로제타 선생님 / 로제타)',
  '답 칸(□, ( ))이 여러 개이거나 모두 써야 정답인 답: 순서대로 쉼표 (예: 3, 6, 9 / 산소, 이산화 탄소)',
  '서술형: 모범 답안 한 문장 그대로. 반드시 들어가야 할 낱말이 정답지에 있으면 문장 뒤에 핵심어: 낱말1, 낱말2',
  '서술형인데 정답지에 "(예)", "예시 답안"처럼 여러 예가 있으면: (예) 답1 / 답2',
  '한 문항에 답 종류가 여러 부분이면(예: 객관식 + 단답, 서술형 문장 + 단답): 부분마다 ; 로 구분 (예: ③ ; 3 cm  또는  선분 ㄱㄴ의 길이는 두 원의 지름의 합과 같습니다. ; 20 cm)',
  '그림을 그리는 문항: 그리기 (그림 + 괄호 답이 함께 있으면 그리기 + 3 cm) — 선생님이 직접 채점하는 문항이 됨',
  '정답이 정해지지 않았거나(자유 답) 선생님이 직접 봐야 하는 문항: 검토',
];

/**
 * @param {object[]} questions 이 평가의 문항(인식 결과) — 문항마다 답 쓰는 법 안내를 붙인다
 * @param {string} title 평가 이름
 */
export function buildAnswerPrompt(questions, title = '') {
  const nos = questions.map((q) => Number(q.no)).filter(Boolean);
  const first = nos.length ? Math.min(...nos) : 1;
  const last = nos.length ? Math.max(...nos) : 1;
  const lines = [
    `너는 초등학교 단원평가 정답을 정리하는 도우미야. 함께 보내는 정답지(PDF·사진 또는 붙여 넣은 글)를 보고,${title ? ` "${title}"의` : ''} 정답을 아래 규칙대로 엑셀 정답 칸에 바로 붙여 넣을 수 있게 위에서 아래로 나열해 줘.`,
    '',
    '[출력 형식 — 꼭 지켜 줘]',
    '- 코드 블록 하나 안에, 문항 순서대로 한 줄에 한 문항씩 정답만 적어 줘.',
    '- 문항 번호는 쓰지 마. 머리글 줄("정답" 같은 제목)도 쓰지 마. 첫 줄이 바로 첫 문항의 정답이야.',
    `- 이 평가는 ${first}번부터 ${last}번까지 ${questions.length}문항이야. 빠진 문항 없이 꼭 ${questions.length}줄을 적어 줘.`,
    '- 한 문항의 정답은 반드시 한 줄에. 답이 길어도 줄을 바꾸지 마.',
    '- 배점: 정답지나 문제지에 문항 배점이 적혀 있으면 정답 뒤에 탭(Tab) 한 번, 그다음 배점 숫자만 적어 줘 (예: 정답<탭>4).',
    '  · 한 문항 안에서 부분마다 점수가 따로 있으면(부분 점수) 정답을 ; 로 나눈 순서대로 배점도 ; 로 나눠 줘 (예: 정답1 ; 정답2<탭>3 ; 2).',
    '  · 배점이 적혀 있지 않으면 배점은 쓰지 말고 정답만 적어 줘 (그러면 100점을 고르게 나눠 줄게).',
    '- 해설, 풀이, 채점 기준, "정답:" 같은 머리말은 쓰지 마.',
    '- 정답지에서 정답을 찾을 수 없거나 확실하지 않은 문항은 그 줄에 검토 라고 적어 줘.',
    '- 코드 블록 밖에는 아무 설명도 쓰지 마.',
    '',
    '[정답 쓰는 규칙]',
    ...RULES.map((r) => `- ${r}`),
    '',
    '[문항별 안내 — 문제지를 보고 이 사이트가 미리 알아낸 답 형식 (이 순서대로 한 줄씩)]',
    ...questions.map((q) => `- ${q.no}번: ${answerHint(q)}`),
    '',
    '[출력 예시 — 배점이 없을 때]',
    '```',
    '③',
    '3 cm',
    '(1)-② (2)-① (3)-③',
    '선분 ㄱㄴ의 길이는 두 원의 지름의 길이의 합과 같습니다. ; 20 cm',
    '그리기',
    '```',
    '',
    '[출력 예시 — 배점이 있을 때]',
    '```',
    '③\t4',
    '3 cm\t4',
    '선분 ㄱㄴ의 길이는 두 원의 지름의 길이의 합과 같습니다. ; 20 cm\t3 ; 2',
    '```',
  ];
  return lines.join('\n');
}
